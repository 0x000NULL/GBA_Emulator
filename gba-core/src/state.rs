//! Savestate support (feature `savestate`): serde helpers for large byte arrays and the
//! `Gba::save_state` / `Gba::load_state` API. The ROM and BIOS image are not stored; `load_state`
//! reattaches them from the live machine. Framebuffer and render scratch buffers are not stored
//! either (the next frame regenerates them).

use serde::de::{self, Deserializer, SeqAccess, Visitor};
use serde::ser::Serializer;
use std::fmt;

struct BytesVisitor<const N: usize>;

impl<'de, const N: usize> Visitor<'de> for BytesVisitor<N> {
    type Value = Vec<u8>;

    fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f, "{N} bytes")
    }

    fn visit_bytes<E: de::Error>(self, v: &[u8]) -> Result<Vec<u8>, E> {
        if v.len() != N {
            return Err(E::invalid_length(v.len(), &self));
        }
        Ok(v.to_vec())
    }

    fn visit_byte_buf<E: de::Error>(self, v: Vec<u8>) -> Result<Vec<u8>, E> {
        if v.len() != N {
            return Err(E::invalid_length(v.len(), &self));
        }
        Ok(v)
    }

    fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<Vec<u8>, A::Error> {
        let mut v = Vec::with_capacity(N);
        while let Some(b) = seq.next_element::<u8>()? {
            v.push(b);
        }
        if v.len() != N {
            return Err(de::Error::invalid_length(v.len(), &self));
        }
        Ok(v)
    }
}

/// `#[serde(with = "crate::state::bytes_box")]` for `Box<[u8; N]>`.
pub mod bytes_box {
    use super::*;

    pub fn serialize<S: Serializer, const N: usize>(v: &Box<[u8; N]>, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_bytes(&v[..])
    }

    pub fn deserialize<'de, D: Deserializer<'de>, const N: usize>(d: D) -> Result<Box<[u8; N]>, D::Error> {
        let v = d.deserialize_bytes(BytesVisitor::<N>)?;
        Ok(v.into_boxed_slice().try_into().map_err(|_| de::Error::custom("length"))?)
    }
}

/// `#[serde(with = "crate::state::bytes_arr")]` for `[u8; N]` with N > 32.
pub mod bytes_arr {
    use super::*;

    pub fn serialize<S: Serializer, const N: usize>(v: &[u8; N], s: S) -> Result<S::Ok, S::Error> {
        s.serialize_bytes(&v[..])
    }

    pub fn deserialize<'de, D: Deserializer<'de>, const N: usize>(d: D) -> Result<[u8; N], D::Error> {
        let v = d.deserialize_bytes(BytesVisitor::<N>)?;
        let mut out = [0u8; N];
        out.copy_from_slice(&v);
        Ok(out)
    }
}

/// Magic + version prefix so stale states are rejected instead of misparsed.
pub const STATE_MAGIC: &[u8; 4] = b"GBAS";
pub const STATE_VERSION: u32 = 5;

#[derive(Debug)]
pub enum StateError {
    BadMagic,
    Version(u32),
    Decode(String),
}

impl fmt::Display for StateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StateError::BadMagic => write!(f, "not a savestate"),
            StateError::Version(v) => write!(f, "savestate version {v} (expected {STATE_VERSION})"),
            StateError::Decode(e) => write!(f, "savestate decode error: {e}"),
        }
    }
}
impl std::error::Error for StateError {}

impl crate::Gba {
    /// Serialize the full machine state (without ROM/BIOS image/framebuffer).
    pub fn save_state(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(0x60000);
        out.extend_from_slice(STATE_MAGIC);
        out.extend_from_slice(&STATE_VERSION.to_le_bytes());
        bincode::serialize_into(&mut out, self).expect("savestate serialization cannot fail");
        out
    }

    /// Restore a state produced by `save_state` for the same ROM. The current ROM and BIOS image
    /// are kept; the framebuffer is regenerated by the next frame.
    pub fn load_state(&mut self, bytes: &[u8]) -> Result<(), StateError> {
        if bytes.len() < 8 || &bytes[..4] != STATE_MAGIC {
            return Err(StateError::BadMagic);
        }
        let ver = u32::from_le_bytes([bytes[4], bytes[5], bytes[6], bytes[7]]);
        if ver != STATE_VERSION {
            return Err(StateError::Version(ver));
        }
        let mut fresh: crate::Gba = bincode::deserialize(&bytes[8..]).map_err(|e| StateError::Decode(e.to_string()))?;
        fresh.bus.cart.set_rom(self.bus.cart.take_rom());
        fresh.bus.bios.set_image(self.bus.bios.take_image());
        // Keep the debugger configuration of the live machine.
        fresh.bus.debug = std::mem::take(&mut self.bus.debug);
        // The bench captures live in the PPU/APU but are debugger state too: carry them over.
        fresh.bus.ppu.debug = self.bus.ppu.debug.take();
        fresh.bus.apu.debug = self.bus.apu.debug.take();
        *self = fresh;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use crate::{Access, BiosMode, Gba, MemoryBus, Options};

    /// mov r0,#1; mov r1,#0x02000000; loop: add r0,r0,#1; str r0,[r1]; b loop
    fn test_rom() -> Vec<u8> {
        let mut rom = vec![0u8; 0x4000];
        rom[0xAC..0xB0].copy_from_slice(b"TEST");
        for (i, w) in [0xE3A0_0001u32, 0xE3A0_1402, 0xE280_0001, 0xE581_0000, 0xEAFF_FFFC].iter().enumerate() {
            rom[i * 4..i * 4 + 4].copy_from_slice(&w.to_le_bytes());
        }
        rom
    }

    #[test]
    fn round_trip_resumes_identically() {
        let opts = Options { bios: BiosMode::Hle, save_type: None };
        let mut a = Gba::new(test_rom(), opts).unwrap();
        a.run_cycles(20_000);
        for i in 0..0x400u32 {
            a.bus.write8(0x0600_0000 + i * 7, (i * 13) as u8, Access::N);
            a.bus.write8(0x0500_0000 + i, (i * 3) as u8, Access::N);
        }
        let state = a.save_state();
        assert!(state.len() > 0x50000, "state holds EWRAM/IWRAM/VRAM ({} bytes)", state.len());

        let r0_at_save = a.cpu.regs.r[0];
        a.run_cycles(30_000);
        let hash_a = a.cpu.state_hash();
        let mem_a = a.bus.read32(0x0200_0000, Access::N);
        let vram_a = a.bus.peek8(0x0600_0007 * 1);

        let mut b = Gba::new(test_rom(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        b.load_state(&state).unwrap();
        assert_eq!(b.cpu.regs.r[0], r0_at_save);
        assert_eq!(b.bus.cart.rom().len(), 0x4000, "ROM reattached");
        assert_eq!(b.bus.peek8(0x0600_0007), vram_a);
        b.run_cycles(30_000);
        assert_eq!(b.cpu.state_hash(), hash_a);
        assert_eq!(b.bus.read32(0x0200_0000, Access::N), mem_a);
        assert_eq!(b.bus.sched.now, a.bus.sched.now);
        assert_eq!(b.bus.ppu.vcount, a.bus.ppu.vcount);
    }

    /// A state saved while an HLE routine waits for guest code it called (SoundDriverMain inside
    /// the game's music player) resumes the routine when the callback returns.
    #[test]
    fn savestate_mid_callback_resumes() {
        use crate::bios::sound::area::info;
        use crate::bios::sound::{ID_NUMBER, SOUND_INFO_PTR};
        // swi SoundDriverMain; b .   and at 0x100 the callback: add r3, r0, #1; bx lr
        let mut rom = test_rom();
        for (i, w) in [0xEF1C_0000u32, 0xEAFF_FFFE].iter().enumerate() {
            rom[i * 4..i * 4 + 4].copy_from_slice(&w.to_le_bytes());
        }
        for (i, w) in [0xE280_3001u32, 0xE12F_FF1E].iter().enumerate() {
            rom[0x100 + i * 4..0x100 + i * 4 + 4].copy_from_slice(&w.to_le_bytes());
        }
        let new = || Gba::new(rom.clone(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        let mut a = new();
        const AREA: u32 = 0x0300_2810;
        a.bus.sound_driver_init(AREA);
        a.bus.write32(AREA + info::FUNC, 0x0800_0100, Access::N);
        a.bus.write32(AREA + info::INTP, 0x1234, Access::N);
        assert!(a.run_until_pc(0x0800_0100, 1_000_000), "inside the callback");
        assert_eq!(a.cpu.regs.r[0], 0x1234);
        assert_eq!(a.cpu.regs.r[14], crate::bios::HLE_CALL_RETURN_ADDR);
        assert_eq!(a.bus.bios.calls.len(), 1);
        assert_eq!(a.bus.read32(SOUND_INFO_PTR, Access::N), AREA);
        assert_eq!(a.bus.read32(AREA, Access::N), ID_NUMBER + 1, "locked");
        let state = a.save_state();

        let mut b = new();
        b.load_state(&state).unwrap();
        assert_eq!(b.bus.bios.calls.len(), 1, "the pending routine is in the state");
        for g in [&mut a, &mut b] {
            assert!(g.run_until_pc(0x0800_0004, 100_000), "back in the caller after the SWI");
            assert!(g.bus.bios.calls.is_empty());
            assert_eq!(g.bus.read32(AREA, Access::N), ID_NUMBER, "unlocked by the resumed routine");
            assert_eq!(g.cpu.regs.r[0], 0, "the caller's r0 (the boot value) is back");
        }
        assert_eq!(a.cpu.state_hash(), b.cpu.state_hash());
    }

    #[test]
    fn rejects_garbage_and_wrong_version() {
        let mut g = Gba::new(test_rom(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        assert!(g.load_state(b"nope").is_err());
        let mut s = g.save_state();
        s[4] = 99;
        assert!(matches!(g.load_state(&s), Err(super::StateError::Version(99))));
    }

    /// The GPIO devices travel in the state: the game's clock offset and the sun level.
    #[test]
    fn gpio_devices_round_trip() {
        let mut rom = test_rom();
        rom[0xAC..0xB0].copy_from_slice(b"U3IE");
        rom[0x2000..0x2008].copy_from_slice(b"SIIRTC_V");
        let new = || Gba::new(rom.clone(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        let mut a = new();
        assert!(a.has_rtc() && a.has_solar());
        a.set_rtc_clock(1_000_000);
        a.bus.cart.gpio.as_mut().unwrap().rtc.as_mut().unwrap().offset = 3600;
        a.set_sun_level(7);
        a.run_cycles(20_000);
        let state = a.save_state();
        let mut b = new();
        b.load_state(&state).unwrap();
        assert_eq!(b.sun_level(), Some(7));
        assert_eq!(b.rtc_time(), a.rtc_time());
        assert_eq!(b.rtc_time(), Some(1_003_600));
        // The frontend reseeds the host clock after a load; the game's offset stays.
        b.set_rtc_clock(2_000_000);
        assert_eq!(b.rtc_time(), Some(2_003_600));
        let plain = Gba::new(test_rom(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        assert!(!plain.has_rtc() && !plain.has_solar() && plain.rtc_time().is_none());
    }

    #[test]
    fn bench_is_not_in_the_state_and_survives_load() {
        let new = || Gba::new(test_rom(), Options { bios: BiosMode::Hle, save_type: None }).unwrap();
        let mut a = new();
        a.run_cycles(20_000);
        let off = a.save_state();
        a.set_bench(true);
        a.set_layer_mute(0x05);
        a.set_channel_mute(0x21);
        let on = a.save_state();
        assert_eq!(off.len(), on.len());
        assert_eq!(off, on, "the bench contributes no bytes to the state");

        // A load keeps the live machine's bench, with its mutes.
        let mut b = new();
        b.set_bench(true);
        b.set_layer_mute(0x05);
        b.set_channel_mute(0x21);
        b.load_state(&off).unwrap();
        assert!(b.bench().is_some() && b.bus.ppu.debug.is_some() && b.bus.apu.debug.is_some());
        assert_eq!((b.layer_mute(), b.channel_mute()), (0x05, 0x21));

        // And a load into a machine without a bench does not conjure one up.
        let mut c = new();
        c.load_state(&on).unwrap();
        assert!(c.bench().is_none() && c.bus.ppu.debug.is_none() && c.bus.apu.debug.is_none());
    }
}