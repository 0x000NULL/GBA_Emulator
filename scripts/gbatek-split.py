"""Split tools/gbatek.htm (GBATEK by Martin Korth) into per-section text files under docs/gbatek/.

Only the GBA reference (sections 0..84) and the ARM CPU reference (661..702) are emitted;
NDS/DSi/3DS chapters are skipped. Run: python scripts/gbatek-split.py
"""
import html, os, re, sys

SRC = os.path.join('tools', 'gbatek.htm')
OUT = os.path.join('docs', 'gbatek')
os.makedirs(OUT, exist_ok=True)
h = open(SRC, encoding='latin-1').read()
anchors = list(re.finditer(r'<A NAME="([^"]+)"></A>\s*\n\s*([^\n<]+)', h))

def to_text(frag: str) -> str:
    frag = re.sub(r'<BR>', '\n', frag, flags=re.I)
    frag = re.sub(r'</TR>', '\n', frag, flags=re.I)
    frag = re.sub(r'<[^>]+>', '', frag)
    frag = html.unescape(frag)
    lines = [l.rstrip() for l in frag.split('\n')]
    out, blank = [], 0
    for l in lines:
        if not l.strip():
            blank += 1
            if blank > 1:
                continue
        else:
            blank = 0
        out.append(l)
    return '\n'.join(out).strip() + '\n'

keep = [i for i, m in enumerate(anchors) if i <= 84 or 661 <= i <= 702]
index = []
for i in keep:
    m = anchors[i]
    end = anchors[i + 1].start() if i + 1 < len(anchors) else len(h)
    name, title = m.group(1), html.unescape(m.group(2).strip())
    body = to_text(h[m.end():end])
    fn = f'{i:03d}-{name}.md'
    with open(os.path.join(OUT, fn), 'w', encoding='utf-8') as f:
        f.write(f'# {title}\n\nSource: https://problemkaputt.de/gbatek.htm#{name}\n\n```\n{body}```\n')
    index.append(f'- [{title}]({fn})')
with open(os.path.join(OUT, 'README.md'), 'w', encoding='utf-8') as f:
    f.write('# GBATEK excerpts\n\nGenerated by `scripts/gbatek-split.py` from GBATEK (Martin Korth, problemkaputt.de). '
            'GBA reference + ARM CPU reference only. Read the relevant file before implementing a subsystem.\n\n')
    f.write('\n'.join(index) + '\n')
print(f'wrote {len(keep)} sections')
